# Checks that every source file carries the SPDX license identifier that
# matches the folder it lives in, plus the copyright line. Run from anywhere;
# exits non-zero and lists the offending files if any are wrong.
#
# Everything in this repository is Apache-2.0 (see LICENSE).
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

expected_license() { echo "Apache-2.0"; }

# Files that are not ours or cannot carry a comment.
skip() {
  case "$1" in
    */LICENSE | NOTICE | *.md | *.json | *.txt | *.svg | *.png | *.ico | *.jar | *.webp | *.woff2) return 0 ;;
    proto/gen/* | *.pb.go) return 0 ;;                      # generated by protoc
    gradlew | gradlew.bat) return 0 ;;  # Gradle's own scripts
    gradle/wrapper/*) return 0 ;;
    */go.sum | */go.mod) return 0 ;;
    *.properties) return 0 ;;
  esac
  return 1
}

# Extensions we consider source code.
is_source() {
  case "$1" in
    *.go | *.java | *.kts | *.proto | *.sh | *.yml | *.yaml | *.toml | */Dockerfile | Dockerfile \
      | *.html | *.css | *.js | *.mjs | *.conf | *.service) return 0 ;;
  esac
  return 1
}

failures=0
checked=0
while IFS= read -r file; do
  [ -f "$file" ] || continue
  is_source "$file" || continue
  skip "$file" && continue
  license="$(expected_license "$file")"
  checked=$((checked + 1))
  head="$(head -n 6 "$file")"
  if ! grep -q "SPDX-License-Identifier: ${license}\( \|\$\| \*/\| -->\)" <<<"$head"; then
    echo "LICENSE   $file (expected SPDX-License-Identifier: $license)"
    failures=$((failures + 1))
  elif ! grep -q "Copyright (c) 20[0-9][0-9] Leoon-X" <<<"$head"; then
    echo "COPYRIGHT $file (expected: Copyright (c) <year> Leoon-X)"
    failures=$((failures + 1))
  fi
done < <(git ls-files --cached --others --exclude-standard)

if [ "$failures" -gt 0 ]; then
  echo "$failures file(s) with missing or wrong license headers"
  exit 1
fi
echo "license headers OK ($checked files checked)"
